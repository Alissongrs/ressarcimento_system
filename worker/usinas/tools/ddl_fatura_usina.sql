-- Faturas de usinas (Thopen) — extração visual. Tabelas novas, separadas das faturas de consumo (FDE).
-- 1 linha por PDF em FATURA_USINA (com o JSON completo) + tabelas filhas para as regras.
-- Idempotente (IF NOT EXISTS). Criado em 30/10/2026 a pedido do Alisson.

CREATE TABLE IF NOT EXISTS FATURA_USINA (
  id_fatura                  CHAR(16)      NOT NULL,
  caminho                    VARCHAR(500)  NOT NULL,
  pasta_usina                VARCHAR(200)  NULL,
  mes_geracao_pasta          CHAR(7)       NULL,
  arquivo                    VARCHAR(300)  NULL,
  paginas                    INT           NULL,
  link_drive                 VARCHAR(600)  NULL,
  duplicata_de               CHAR(16)      NULL,
  tipo_documento             VARCHAR(30)   NULL,
  distribuidora              VARCHAR(200)  NULL,
  distribuidora_sigla        VARCHAR(60)   NULL,
  distribuidora_cnpj         VARCHAR(20)   NULL,
  nf_numero                  VARCHAR(40)   NULL,
  nf_serie                   VARCHAR(10)   NULL,
  nf_chave_acesso            VARCHAR(60)   NULL,
  nf_substituida             VARCHAR(60)   NULL,
  data_emissao               DATE          NULL,
  titular_nome               VARCHAR(250)  NULL,
  titular_cnpj_cpf           VARCHAR(20)   NULL,
  uc                         VARCHAR(40)   NULL,
  instalacao                 VARCHAR(40)   NULL,
  classificacao              VARCHAR(250)  NULL,
  grupo                      VARCHAR(2)    NULL,
  subgrupo                   VARCHAR(6)    NULL,
  modalidade_tarifaria       VARCHAR(30)   NULL,
  modalidade_gd              VARCHAR(80)   NULL,
  mes_referencia             CHAR(7)       NULL,
  data_vencimento            DATE          NULL,
  leitura_anterior           DATE          NULL,
  leitura_atual              DATE          NULL,
  dias_faturados             INT           NULL,
  total_a_pagar              DECIMAL(15,2) NULL,
  total_nota_fiscal          DECIMAL(15,2) NULL,
  total_icms                 DECIMAL(15,2) NULL,
  total_pis                  DECIMAL(15,2) NULL,
  total_cofins               DECIMAL(15,2) NULL,
  total_pis_cofins           DECIMAL(15,2) NULL,
  cosip                      DECIMAL(15,2) NULL,
  kwh_injetada_total         DECIMAL(18,3) NULL,
  kwh_compensada_total       DECIMAL(18,3) NULL,
  demanda_contratada_kw      DECIMAL(14,3) NULL,
  demanda_geracao_kw         DECIMAL(14,3) NULL,
  soma_itens                 DECIMAL(15,2) NULL,
  validacao_ok               TINYINT       NULL,
  n_divergencias_impressas   INT           NULL,
  n_ilegiveis                INT           NULL,
  versao_formato             INT           NULL,
  extraido_em                DATETIME      NULL,
  carregado_em               DATETIME      NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  metodo                     VARCHAR(10)   NOT NULL DEFAULT 'visual',
  dados_json                 JSON          NOT NULL,
  PRIMARY KEY (id_fatura),
  KEY idx_fu_uc (uc),
  KEY idx_fu_dist_mes (distribuidora_sigla, mes_referencia),
  KEY idx_fu_usina (pasta_usina, mes_geracao_pasta)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS FATURA_USINA_ITENS (
  id                     BIGINT        NOT NULL AUTO_INCREMENT,
  id_fatura              CHAR(16)      NOT NULL,
  ordem                  INT           NOT NULL,
  pagina                 INT           NULL,
  secao_impressa         VARCHAR(120)  NULL,
  codigo                 VARCHAR(30)   NULL,
  descricao              VARCHAR(400)  NULL,
  mes_ref                VARCHAR(10)   NULL,
  componente             VARCHAR(40)   NULL,
  posto                  VARCHAR(20)   NULL,
  quantidade_registrada  DECIMAL(20,6) NULL,
  quantidade_faturada    DECIMAL(20,6) NULL,
  unidade                VARCHAR(20)   NULL,
  tarifa_com_tributos    DECIMAL(20,10) NULL,
  tarifa_sem_tributos    DECIMAL(20,10) NULL,
  valor                  DECIMAL(15,2) NULL,
  valor_sem_tributos     DECIMAL(15,2) NULL,
  base_icms              DECIMAL(15,2) NULL,
  aliquota_icms          DECIMAL(8,4)  NULL,
  icms                   DECIMAL(15,2) NULL,
  base_pis_cofins        DECIMAL(15,2) NULL,
  aliquota_pis           DECIMAL(8,4)  NULL,
  pis                    DECIMAL(15,2) NULL,
  aliquota_cofins        DECIMAL(8,4)  NULL,
  cofins                 DECIMAL(15,2) NULL,
  pis_cofins             DECIMAL(15,2) NULL,
  nf_referencia          VARCHAR(60)   NULL,
  colunas_originais      JSON          NULL,
  PRIMARY KEY (id),
  KEY idx_fui_fatura (id_fatura, ordem),
  KEY idx_fui_comp (componente, posto)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS FATURA_USINA_MEDICOES (
  id                     BIGINT        NOT NULL AUTO_INCREMENT,
  id_fatura              CHAR(16)      NOT NULL,
  ordem                  INT           NOT NULL,
  pagina                 INT           NULL,
  tabela_origem          VARCHAR(150)  NULL,
  medidor                VARCHAR(60)   NULL,
  grandeza               VARCHAR(120)  NULL,
  posto                  VARCHAR(20)   NULL,
  leitura_anterior       DECIMAL(20,4) NULL,
  leitura_atual          DECIMAL(20,4) NULL,
  constante              DECIMAL(18,6) NULL,
  perdas_pct             DECIMAL(8,4)  NULL,
  ajuste                 DECIMAL(20,4) NULL,
  consumo                DECIMAL(20,4) NULL,
  consumo_faturado       DECIMAL(20,4) NULL,
  fator_potencia         DECIMAL(10,4) NULL,
  ajuste_fator_potencia  DECIMAL(20,4) NULL,
  unidade                VARCHAR(20)   NULL,
  data_hora_registro     VARCHAR(30)   NULL,
  leitura_arredondada    TINYINT       NULL,
  colunas_originais      JSON          NULL,
  PRIMARY KEY (id),
  KEY idx_fum_fatura (id_fatura, ordem)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS FATURA_USINA_DEMANDA (
  id                          BIGINT        NOT NULL AUTO_INCREMENT,
  id_fatura                   CHAR(16)      NOT NULL,
  ordem                       INT           NOT NULL,
  pagina                      INT           NULL,
  tipo                        VARCHAR(20)   NULL,
  posto                       VARCHAR(20)   NULL,
  contratada_kw               DECIMAL(14,3) NULL,
  medida_kw                   DECIMAL(14,3) NULL,
  faturada_kw                 DECIMAL(14,3) NULL,
  faturada_ultrapassagem_kw   DECIMAL(14,3) NULL,
  nao_consumida_kw            DECIMAL(14,3) NULL,
  data_hora                   VARCHAR(30)   NULL,
  rotulo                      VARCHAR(300)  NULL,
  colunas_originais           JSON          NULL,
  PRIMARY KEY (id),
  KEY idx_fud_fatura (id_fatura, ordem)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS FATURA_USINA_GD (
  id                BIGINT        NOT NULL AUTO_INCREMENT,
  id_fatura         CHAR(16)      NOT NULL,
  ordem             INT           NOT NULL,
  pagina            INT           NULL,
  tipo              VARCHAR(30)   NULL,
  posto             VARCHAR(20)   NULL,
  kwh               DECIMAL(20,3) NULL,
  mes_ref           VARCHAR(10)   NULL,
  ref_expiracao     VARCHAR(20)   NULL,
  unidade_impressa  VARCHAR(20)   NULL,
  uc_beneficiaria   VARCHAR(40)   NULL,
  percentual        DECIMAL(10,4) NULL,
  rotulo            VARCHAR(600)  NULL,
  PRIMARY KEY (id),
  KEY idx_fug_fatura (id_fatura, ordem),
  KEY idx_fug_tipo (tipo)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS FATURA_USINA_HISTORICO (
  id                    BIGINT        NOT NULL AUTO_INCREMENT,
  id_fatura             CHAR(16)      NOT NULL,
  ordem                 INT           NOT NULL,
  pagina                INT           NULL,
  mes                   VARCHAR(10)   NULL,
  serie                 VARCHAR(30)   NULL,
  posto                 VARCHAR(20)   NULL,
  valor                 DECIMAL(20,4) NULL,
  unidade               VARCHAR(20)   NULL,
  unidade_original      VARCHAR(20)   NULL,
  faturado_pela_media   TINYINT       NULL,
  PRIMARY KEY (id),
  KEY idx_fuh_fatura (id_fatura, ordem)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;


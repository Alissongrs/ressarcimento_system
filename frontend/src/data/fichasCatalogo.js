export function fichaInfo(codigo) {
  if (!codigo) return undefined;
  const k = String(codigo).toUpperCase().trim();
  return FICHAS_CATALOGO[k];
}

// String multi-linha pronta para o atributo title= (tooltip nativo do browser).
export function fichaTooltip(codigo) {
  const info = fichaInfo(codigo);
  if (!info) return String(codigo || '');
  return `${codigo} — ${info.nome}\n\nO que é: ${info.oque}\n\nComo conferir: ${info.conferir}\n\nBase: ${info.base}`;
}

export const FICHAS_LISTA = Object.entries(FICHAS_CATALOGO).map(([codigo, v]) => ({ codigo, ...v }));
